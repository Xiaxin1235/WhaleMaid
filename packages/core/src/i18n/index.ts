/** Translate stable verification reason/status codes while retaining unknown diagnostics. */
export function verificationText(locale: Locale, code: string): string {
  const keys: Record<string, MessageKey> = {
    'report-only': 'reasonReport',
    'acceptance-tampering': 'reasonTampering',
    tampering: 'reasonTampering',
    'verification-regression': 'reasonRegression',
    'verification-improved': 'reasonImproved',
    'verification-passed': 'reasonPassed',
    'verification-still-failing': 'reasonStillFailing',
    'no-verification-commands': 'reasonNoCommands',
    'not-scorable': 'reasonNoCommands',
    'no-changes': 'reasonNoChanges',
    'missing-command-evidence': 'reasonMissing',
    'session-observation-unavailable': 'reasonMissing',
    'command-error-or-timeout': 'reasonError',
    'empty-report': 'reasonEmpty',
    'analysis-changed-files': 'reasonAnalysisChanged',
    'fix-rounds-exhausted': 'reasonFixExhausted',
    stalled: 'reasonStalled',
    neutral: 'progressNeutral',
    'verification-unknown': 'reasonUnknownRepeated',
    improved: 'progressImproved',
    unchanged: 'progressUnchanged',
    regressed: 'progressRegressed',
    unknown: 'progressUnknown',
    passed: 'commandPassed',
    failed: 'commandFailed',
    error: 'commandError',
    timeout: 'commandTimeout',
  }
  if (code.startsWith('goal-completed:'))
    return t(locale, 'goalCompletedNotice', { checkpoint: code.slice('goal-completed:'.length) })
  if (code.startsWith('next-task-ready:')) return t(locale, 'nextReadyReason')
  if (code === 'planner-need-user') return t(locale, 'plannerNeedUserReason')
  if (code.startsWith('denied-actions:')) return t(locale, 'reasonDenied', { count: code.slice(15) })
  return keys[code] ? t(locale, keys[code]) : code
}

